import os
import glob
import cv2
import numpy as np
from tqdm import tqdm

def process_bdd100k_drivable(raw_mask_path, target_width=640, target_height=360):
    """
    Converts raw BDD100K drivable area masks to binary masks.
    BDD100K drivable annotations:
    - 0: Background
    - 1: Main Drivable Lane
    - 2: Alternative Drivable Lane
    """
    mask = cv2.imread(raw_mask_path, cv2.IMREAD_GRAYSCALE)
    if mask is None:
        return None
        
    # Combine main (1) and alternative (2) drivable areas into single binary mask (255)
    drivable_binary = np.where((mask == 1) | (mask == 2), 255, 0).astype(np.uint8)
    drivable_resized = cv2.resize(drivable_binary, (target_width, target_height), interpolation=cv2.INTER_NEAREST)
    return drivable_resized

def process_idd_lite_drivable(raw_mask_path, target_width=640, target_height=360):
    """
    Converts raw IDD Lite segmentation masks to binary drivable space.
    IDD Lite annotations:
    - Class 0: Road
    - Class 1: Drivable Fallback / Unpaved Road
    """
    mask = cv2.imread(raw_mask_path, cv2.IMREAD_GRAYSCALE)
    if mask is None:
        return None
        
    # Map both paved road (0) and unpaved/fallback drivable surfaces (1)
    drivable_binary = np.where((mask == 0) | (mask == 1), 255, 0).astype(np.uint8)
    drivable_resized = cv2.resize(drivable_binary, (target_width, target_height), interpolation=cv2.INTER_NEAREST)
    return drivable_resized

def convert_dataset_to_twinlitenet_format(raw_dir, processed_dir, dataset_type="bdd100k"):
    """
    Parses raw data directory and extracts aligned images and dual-channel binary masks.
    """
    print(f"\nProcessing raw {dataset_type.upper()} dataset from: {raw_dir}")
    
    images_dir = os.path.join(raw_dir, "images")
    drivable_raw_dir = os.path.join(raw_dir, "labels", "drivable")
    
    if not os.path.exists(images_dir):
        print(f"[Info] Raw directory '{images_dir}' not found. Skipping raw parsing.")
        print("  (You can run with synthetic mock data generated by dataset.py in the meantime).")
        return 0

    image_files = sorted(glob.glob(os.path.join(images_dir, "*.[jJ][pP][gG]"))) + \
                  sorted(glob.glob(os.path.join(images_dir, "*.[pP][nN][gG]")))
                  
    count = 0
    for img_path in tqdm(image_files, desc=f"Converting {dataset_type}"):
        filename = os.path.basename(img_path)
        name_stem = os.path.splitext(filename)[0]
        
        # Determine target mask path
        mask_path = os.path.join(drivable_raw_dir, name_stem + ".png")
        if not os.path.exists(mask_path):
            continue
            
        # Parse mask based on dataset source
        if dataset_type.lower() == "bdd100k":
            drivable_mask = process_bdd100k_drivable(mask_path)
        else:
            drivable_mask = process_idd_lite_drivable(mask_path)
            
        if drivable_mask is None:
            continue
            
        # Resize raw RGB driving image to match tensor dimensions (640x360)
        img = cv2.imread(img_path)
        img_resized = cv2.resize(img, (640, 360), interpolation=cv2.INTER_LINEAR)
        
        # Blank lane mask as fallback for unstructured scenes where lane files are absent
        lane_mask = np.zeros((360, 640), dtype=np.uint8)
        
        # Save structured outputs to processed directory
        cv2.imwrite(os.path.join(processed_dir, "images", filename), img_resized)
        cv2.imwrite(os.path.join(processed_dir, "masks_drivable", filename), drivable_mask)
        cv2.imwrite(os.path.join(processed_dir, "masks_lanes", filename), lane_mask)
        count += 1

    print(f"Successfully converted and saved {count} samples to '{processed_dir}'.")
    return count

if __name__ == "__main__":
    print("=" * 60)
    print("        RAW DATASET INGESTION & CONVERSION PIPELINE")
    print("=" * 60)
    
    # Process raw BDD100K and IDD Lite samples if available in raw directory
    convert_dataset_to_twinlitenet_format(
        raw_dir="data/raw/bdd100k",
        processed_dir="data/processed/train",
        dataset_type="bdd100k"
    )
    
    convert_dataset_to_twinlitenet_format(
        raw_dir="data/raw/idd_lite",
        processed_dir="data/processed/train",
        dataset_type="idd_lite"
    )
    print("=" * 60)